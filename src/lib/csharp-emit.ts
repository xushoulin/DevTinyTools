/**
 * C# class emission.
 *
 * The mapping problems are C#'s own, so the rules differ from Go and Java:
 *
 * 1. **Nullable reference types carry the optionality.** With `#nullable
 *    enable`, `string?` and `Customer?` say "this key may be absent or null"
 *    and the compiler enforces it. Value types answer the same question with
 *    `long?` / `bool?`. A generator that ignores this compiles with a wall of
 *    CS8618 warnings and fails at runtime on the first missing key.
 * 2. **Non-nullable members need an initialiser.** `public string Name { get;
 *    set; }` is legal but warns CS8618, so required strings get
 *    `= string.Empty;` and required classes/lists get `= new();`. The file is
 *    then warning-free without changing behaviour.
 * 3. **Naming diverges from the wire.** `coupon_code` becomes `CouponCode`
 *    (PascalCase is the C# convention), so `[JsonPropertyName]` keeps the JSON
 *    name. Without it System.Text.Json deserialises that property as null.
 * 4. **Every class is top-level.** C# allows many classes per file, unlike
 *    Java, so nesting them would be noise: the whole document is a flat list of
 *    classes in one file.
 */

import { nameObjectTypes, toPascalCase, type InferredType } from "./type-infer";

export interface CsharpEmitOptions {
  rootName: string;
  /** File-scoped namespace declaration, e.g. `MyApp.Models`. Omitted when blank. */
  namespace?: string;
  /** Emit `[JsonPropertyName]` when the C# name differs from the JSON key. */
  attributes: boolean;
  indent: 2 | 4;
}

export interface CsharpEmitResult {
  code: string;
  typeCount: number;
  lineCount: number;
}

const VALUE_TYPES = new Set(["long", "double", "bool"]);

export function emitCsharp(root: InferredType, options: CsharpEmitOptions): CsharpEmitResult {
  const unit = " ".repeat(options.indent);
  let named = nameObjectTypes(root, options.rootName);
  const byShape = new Map<InferredType, string>();

  const preamble: string[] = [];

  if (root.kind !== "object") {
    const element = root.kind === "array" ? root.items : null;
    const elementShape = element && element.kind === "object" ? element : null;

    if (!elementShape) {
      // A bare primitive or primitive array root needs no class. Say so rather
      // than inventing a wrapper type the API never sends.
      return {
        code: `// The JSON root is ${describe(root)}, which needs no class:\n//   ${csharpType(root, false, byShape)} value = ...;\n// Paste an object or an array of objects to generate classes.\n`,
        typeCount: 0,
        lineCount: 3,
      };
    }

    // Name the element class after the root — and re-derive every nested name
    // from it, so the children are OrderCustomer rather than OrderItemCustomer.
    named = nameObjectTypes(elementShape, options.rootName);
    preamble.push(
      `// The JSON root is an array. This file models one element; hold them in List<${options.rootName}>.`,
    );
  }

  for (const entry of named) byShape.set(entry.shape, entry.name);

  const declarations = named;

  const usesList = declarations.some((entry) => entry.shape.properties.some((p) => containsArray(p.type)))
    || containsArray(root);
  const usesAttributes = options.attributes && declarations.some((entry) =>
    entry.shape.properties.some((p) => propertyName(p.name) !== p.name),
  );
  // `?` only compiles inside a nullable annotations context, and it can appear
  // deeper than the property itself: `List<string?>` from an array that held a
  // null. Scan the whole type, not just its top level.
  const usesNullable = declarations.some((entry) =>
    entry.shape.properties.some((p) => p.optional || anyNull(p.type)),
  );

  const lines: string[] = ["// <auto-generated />"];

  if (preamble.length > 0) {
    lines.push("");
    lines.push(...preamble);
  }

  if (usesNullable) {
    lines.push("");
    lines.push("#nullable enable");
  }

  const usings: string[] = [];
  if (usesList) usings.push("using System.Collections.Generic;");
  if (usesAttributes) usings.push("using System.Text.Json.Serialization;");

  if (usings.length > 0) {
    lines.push("");
    lines.push(...usings);
  }

  if (options.namespace?.trim()) {
    lines.push("");
    lines.push(`namespace ${options.namespace.trim()};`);
  }

  let typeCount = 0;

  for (const entry of declarations) {
    lines.push("");
    lines.push(`public class ${entry.name}`);
    lines.push("{");
    typeCount += 1;

    const used = new Set<string>();

    for (const property of entry.shape.properties) {
      const nullable = isNullable(property.optional, property.type);
      const type = csharpType(property.type, nullable, byShape);
      const name = uniqueName(propertyName(property.name), used);
      used.add(name);

      if (options.attributes && name !== property.name) {
        lines.push(`${unit}[JsonPropertyName("${property.name.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}")]`);
      }

      const initialiser = needsInitialiser(type, nullable)
        ? ` = ${initialiserFor(type)}`
        : "";

      lines.push(`${unit}public ${type} ${name} { get; set; }${initialiser}`);
    }

    lines.push("}");
  }

  const code = `${lines.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd()}\n`;

  return {
    code,
    typeCount,
    lineCount: code.split("\n").filter((line) => line.trim().length > 0).length,
  };
}

/** `coupon_code` → `CouponCode`; digits cannot start an identifier. */
export function propertyName(jsonName: string): string {
  const pascal = toPascalCase(jsonName);
  if (!pascal) return "Value";
  return /^[0-9]/.test(pascal) ? `Field${pascal}` : pascal;
}

/** Two keys that differ only in punctuation collapse onto one C# name. */
function uniqueName(name: string, used: Set<string>): string {
  if (!used.has(name)) return name;
  let suffix = 2;
  while (used.has(`${name}${suffix}`)) suffix += 1;
  return `${name}${suffix}`;
}

/**
 * Map an inferred type to a C# type. `nullable` appends `?`, which is legal for
 * both value types and (under `#nullable enable`) reference types — the same
 * annotation expresses Go's pointer and Java's wrapper distinction.
 */
export function csharpType(
  type: InferredType,
  nullable: boolean,
  byShape: Map<InferredType, string>,
): string {
  const base = baseType(type, byShape);
  return (nullable || containsNull(type)) && !base.endsWith("?") ? `${base}?` : base;
}

function baseType(type: InferredType, byShape: Map<InferredType, string>): string {
  switch (type.kind) {
    case "string":
      return "string";
    case "number":
      return type.integer ? "long" : "double";
    case "boolean":
      return "bool";
    case "object":
      return byShape.get(type) ?? "object";
    case "array":
      return `List<${csharpType(type.items, false, byShape)}>`;
    case "union": {
      // null is not a type in C#: it is what `?` on the member expresses.
      const members = type.options.filter((option) => option.kind !== "null");
      if (members.length === 0) return "object";
      const mapped = [...new Set(members.map((option) => baseType(option, byShape)))];
      if (mapped.length === 1) return mapped[0];
      // long + double widens to double; a genuinely mixed field is object,
      // which System.Text.Json materialises as JsonElement.
      if (mapped.every((name) => name === "long" || name === "double")) return "double";
      return "object";
    }
    case "null":
    case "unknown":
      return "object";
  }
}

function isNullable(optional: boolean, type: InferredType): boolean {
  return optional || containsNull(type);
}

/** True when `null` appears anywhere in the type. */
function containsNull(type: InferredType): boolean {
  if (type.kind === "null") return true;
  if (type.kind === "union") return type.options.some(containsNull);
  return false;
}

function containsArray(type: InferredType): boolean {
  if (type.kind === "array") return true;
  if (type.kind === "object") return type.properties.some((property) => containsArray(property.type));
  if (type.kind === "union") return type.options.some(containsArray);
  return false;
}

/** True when a `?` would be emitted anywhere inside this type. */
function anyNull(type: InferredType): boolean {
  if (type.kind === "null") return true;
  if (type.kind === "union") return type.options.some(anyNull);
  if (type.kind === "array") return anyNull(type.items);
  return false;
}

function bareType(type: string): string {
  return type.endsWith("?") ? type.slice(0, -1) : type;
}

/**
 * A non-nullable reference member without an initialiser triggers CS8618, so
 * the generated file would not be warning-free. Required value members are
 * already safe at their default.
 */
function needsInitialiser(type: string, nullable: boolean): boolean {
  if (nullable || type.endsWith("?")) return false;
  return !VALUE_TYPES.has(bareType(type));
}

function initialiserFor(type: string): string {
  const bare = bareType(type);
  if (bare === "string") return "string.Empty;";
  if (bare === "object") return "null!;";
  return "new();";
}

function describe(type: InferredType): string {
  switch (type.kind) {
    case "array":
      return `an array of ${describe(type.items)}`;
    case "union":
      return "a mixed value";
    default:
      return type.kind;
  }
}
